const assert = require('node:assert/strict');
async function exerciseAnalysis(page) {
  await page.getByRole('button', { name: 'Upload', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Upload dataset' }).click();
  await page.locator('summary').filter({ hasText: 'Advanced training settings' }).click();
  await page.getByRole('button', { name: 'Reset training settings', exact: true }).click();
  await page.locator('.live-file input').setInputFiles({ name: 'analysis.csv', mimeType: 'text/csv', buffer: Buffer.from('a,b,label\n0,0,no\n0,1,yes\n1,0,yes\n1,1,no\n') });
  await page.getByLabel('Maximum depth', { exact: true }).fill('2');
  await page.getByLabel('Leaf penalty', { exact: true }).fill('.25');
  await page.getByLabel('Rashomon multiplier', { exact: true }).fill('2');
  await page.getByLabel('Allow Abstain leaves', { exact: true }).check();
  await page.getByLabel('Abstention cost', { exact: true }).fill('.25');
  const posted = page.waitForResponse(r => r.url().endsWith('/api/session') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Start ArborEnum', exact: true }).click();
  const sid = (await (await posted).json()).session_id;
  await page.waitForFunction(sid => window.ARBORENUM_CURRENT_BUILDER_PAYLOAD?.graph?.metadata?.session_id === sid, sid);
  await page.waitForFunction(async () => ['finished', 'stopped'].includes((await (await fetch('/api/session')).json()).phase));
  await page.getByRole('button', { name: 'Analyze', exact: true }).click();
  const analysis = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Calculate exact ranges', exact: true }).click();
  const response = await analysis;
  assert.equal(response.status(), 200, await response.text());
  const result = await response.json();
  assert.equal(result.exact, true);
  assert.ok(BigInt(result.tree_count) > 1n);
  assert.equal(result.permutation, 'expectation_over_all_permutations');
  assert.equal(result.importance.length, 2);
  assert.equal(result.disagreement.length, 4);
  for (const row of result.disagreement) assert.equal(row.counts.reduce((a, b) => a + BigInt(b), 0n), BigInt(result.tree_count));
  await page.locator('.analysis-importance tbody tr').first().waitFor();
  assert.equal(await page.locator('.analysis-importance tbody tr').count(), 2);
  assert.equal(await page.locator('.analysis-violin').count(), 1);
  await page.getByLabel('Analysis maximum leaves', { exact: true }).fill('1');
  await page.getByLabel('Analysis maximum abstained samples', { exact: true }).fill('0');
  const capped = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Calculate exact ranges', exact: true }).click();
  const limited = await (await capped).json();
  assert.equal(limited.leaf_distribution.length, 1);
  assert.equal(limited.leaf_distribution[0].value, 1);
  assert.equal(limited.abstention_distribution[0].value, 0);
  await page.getByLabel('Close analysis', { exact: true }).click();
  await page.locator('.split-choice').first().click();
  await page.getByRole('button', { name: 'Constrained', exact: true }).click();
  await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
  await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
  const infeasible = page.waitForResponse(r => r.url().includes('/api/complete?'));
  await page.getByRole('button', { name: 'Build optimal constrained completion', exact: true }).click();
  assert.equal((await infeasible).status(), 400);
  await page.locator('.constraint-message').filter({ hasText: 'No completion satisfies' }).waitFor();
  assert.equal(await page.locator('.arborenum-node-split').count(), 1);
  await page.locator('.constraint-close').click();
  await page.locator('.arborenum-node-split').click();
  await page.getByRole('button', { name: 'Constrained', exact: true }).click();
  await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
  await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
  const completion = page.waitForResponse(r => r.url().includes('/api/complete?'));
  await page.getByRole('button', { name: 'Build optimal constrained completion', exact: true }).click();
  const filledResponse = await completion;
  assert.equal(filledResponse.status(), 200, await filledResponse.text());
  const filled = await filledResponse.json();
  assert.equal(filled.leaves, 1); assert.equal(filled.abstained_samples, 0); assert.equal(filled.tree.kind, 'leaf');
  await page.locator('.constraint-modal').waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'Analyze', exact: true }).click();
  const fixed = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Calculate exact ranges', exact: true }).click();
  const fixedResult = await (await fixed).json();
  assert.equal(fixedResult.tree_count, '1');
  for (const row of fixedResult.disagreement) assert.equal(row.disagreement, 0);
  await page.getByLabel('Close analysis', { exact: true }).click();
  for (const mode of ['Ensure prediction', 'Both']) {
    await page.locator('.arborenum-node-leaf').click();
    await page.getByRole('button', { name: 'Constrained', exact: true }).click();
    await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
    await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
    await page.getByRole('button', { name: mode, exact: true }).click();
    if (mode === 'Both') await page.locator('.constraint-check-grid input').first().check();
    await page.getByLabel('Prediction to ensure', { exact: true }).selectOption('1');
    const pending = page.waitForResponse(r => r.url().includes('/api/complete?'));
    await page.getByRole('button', { name: mode === 'Both' ? 'Build optimal completion satisfying both' : 'Build optimal constrained completion', exact: true }).click();
    const response = await pending;
    assert.equal(response.status(), 200, await response.text());
    const result = await response.json();
    assert.equal(result.leaves, 1); assert.equal(result.abstained_samples, 0); assert.equal(result.tree.prediction, 1);
    await page.locator('.constraint-modal').waitFor({ state: 'detached' });
  }
  assert.equal(await page.evaluate(async () => (await (await fetch('/api/session')).json()).full_graph_exports), 0);
  console.log('Exact native analysis menu, class counts, violin, whole-tree caps and fixed-tree analysis passed');
}
module.exports = { exerciseAnalysis };
