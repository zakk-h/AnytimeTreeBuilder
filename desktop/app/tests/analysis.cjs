const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
async function exerciseAnalysis(page) {
  await page.getByRole('button', { name: 'Upload', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Upload dataset' }).click();
  await page.locator('summary').filter({ hasText: 'Advanced training settings' }).click();
  await page.getByRole('button', { name: 'Reset training settings', exact: true }).click();
  await page.locator('.live-file input').setInputFiles({ name: 'analysis.csv', mimeType: 'text/csv', buffer: Buffer.from('a,b,label\n0,0,no\n0,1,yes\n1,0,yes\n1,1,no\n') });
  await page.getByLabel('Maximum depth', { exact: true }).fill('2');
  await page.getByLabel('Leaf penalty', { exact: true }).fill('.25');
  await page.getByLabel('Rashomon multiplier', { exact: true }).fill('2');
  await page.getByLabel('Allow Abstain leaves', { exact: true }).check();
  await page.getByLabel('Abstention cost', { exact: true }).fill('.25');
  const posted = page.waitForResponse(r => r.url().endsWith('/api/session') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Start ArborEnum', exact: true }).click();
  const sid = (await (await posted).json()).session_id;
  await page.waitForFunction(sid => window.ARBORENUM_CURRENT_BUILDER_PAYLOAD?.graph?.metadata?.session_id === sid, sid);
  await page.waitForFunction(async () => ['finished', 'stopped'].includes((await (await fetch('/api/session')).json()).phase));
  const capacity = await page.evaluate(async () => (await (await fetch('/api/session')).json()).graph_budget);
  await page.locator('.live-budget summary').click();
  const slider = page.getByRole('slider', { name: 'Objective budget', exact: true });
  const lower = page.waitForResponse(r => r.url().includes('/api/budget?') && r.request().postDataJSON().budget === 2);
  const budgetInput = page.getByRole('spinbutton', { name: 'Objective budget value', exact: true });
  await budgetInput.fill('.5');
  assert.ok((await page.locator('.live-budget summary').innerText()).includes('0.5'));
  assert.equal(await page.locator('.live-budget-popover p').count(), 0);
  await budgetInput.press('Enter');
  const lowered = await (await lower).json();
  assert.equal(lowered.active_budget, 2); assert.equal(lowered.graph_budget, capacity);
  await page.waitForFunction(() => document.querySelectorAll('.split-choice').length === 0 && document.querySelectorAll('.leaf-choice').length === 1);
  assert.ok((await page.locator('.leaf-choice').innerText()).includes('Abstain'));
  const lowerView = await page.evaluate(async sid => (await (await fetch('/api/node?session_id=' + sid, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ tree: { uid: 0, kind: 'choice' }, active_uid: 0 }) })).json()), sid);
  assert.equal(lowerView.options.splits.length, 0);
  assert.equal(lowerView.options.leaves.length, 1); assert.equal(lowerView.options.leaves[0].prediction, -1);
  const restore = page.waitForResponse(r => r.url().includes('/api/budget?') && r.request().postDataJSON().budget === capacity);
  await slider.focus(); await slider.press('Home');
  for (let i = 0; i < capacity; ++i) await slider.press('ArrowRight');
  assert.equal((await (await restore).json()).active_budget, capacity);
  await page.locator('.live-budget summary').click();
  await page.waitForFunction(async () => { const s = await (await fetch('/api/session')).json(); return s.active_budget === s.graph_budget; });
  let releaseAnalysis;
  const held = new Promise(resolve => { releaseAnalysis = resolve; });
  const holdResponse = async route => { const response = await route.fetch(); await held; await route.fulfill({ response }); };
  const reportProgress = route => route.fulfill({ json: { stage: 3, completed_features: 1, feature_count: 2, current_feature: 'b' } });
  await page.route('**/api/analyze?*', holdResponse);
  await page.route('**/api/analysis-progress?*', reportProgress);
  const analysis = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Analyze', exact: true }).click();
  await page.getByText('Computing feature importance · 1/2 features complete · b', { exact: true }).waitFor();
  assert.equal(await page.getByRole('progressbar', { name: 'Analysis stages completed' }).getAttribute('value'), '3.5');
  assert.equal(await page.getByText('Calculating…', { exact: true }).count(), 1);
  releaseAnalysis();
  const response = await analysis;
  await page.unroute('**/api/analyze?*', holdResponse);
  await page.unroute('**/api/analysis-progress?*', reportProgress);
  assert.equal(response.status(), 200, await response.text());
  const result = await response.json();
  assert.equal(result.exact, true);
  assert.ok(BigInt(result.tree_count) > 1n);
  assert.equal(result.permutation, 'expectation_over_all_permutations');
  assert.equal(result.importance.length, 2);
  assert.equal(result.disagreement.length, 4);
  for (const row of result.disagreement) {
    assert.equal(row.counts.reduce((a, b) => a + BigInt(b), 0n), BigInt(result.tree_count));
    assert.ok(Math.abs(row.disagreement - (1 - Math.max(...row.probabilities))) < 1e-12);
  }
  assert.equal(result.disagreement_metric, 'variation_ratio');
  await page.locator('.analysis-importance tbody tr').first().waitFor();
  assert.equal(await page.locator('.analysis-importance tbody tr').count(), 2);
  assert.equal(await page.locator('.analysis-violin').count(), 1);
  assert.equal(await page.locator('.analysis-metrics').innerText(), `Feasible completions\n${BigInt(result.tree_count).toLocaleString()}\nAccuracy on predicted samples\n${await page.locator('.analysis-metrics b').nth(1).innerText()}\nNumber of leaves\n${result.leaf_distribution[0].value} – ${result.leaf_distribution[result.leaf_distribution.length - 1].value}`);
  assert.equal(await page.getByText('Training samples', { exact: true }).count(), 0);
  const leavesChart = page.locator('.analysis-distribution-leaves');
  await leavesChart.locator('rect').first().hover();
  const firstBin = result.leaf_distribution[0];
  assert.ok((await leavesChart.getByRole('tooltip').innerText()).includes(`${firstBin.value} leaves · ${BigInt(firstBin.count).toLocaleString()} models`));
  assert.equal(await page.getByText('View distribution', { exact: true }).count(), 0);
  assert.equal(await page.getByText(/Exact for the graph available/).count(), 0);
  const abstentionChart = page.locator('.analysis-distribution-abstention');
  await abstentionChart.locator('rect').last().focus();
  assert.ok((await abstentionChart.getByRole('tooltip').innerText()).includes('% abstained'));
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export analysis', exact: true }).click();
  const download = await downloadEvent;
  const exported = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
  assert.deepEqual(exported, result, 'Export should retain every analysis field');
  assert.equal(exported.partial_tree.kind, 'choice');
  assert.ok(exported.training_settings && exported.timings && exported.objective_distribution);
  await page.screenshot({ path: '/tmp/atb-analysis-menu.png' });
  assert.equal(await page.locator('.analysis-dialog input').count(), 0, 'Analysis should have no cap controls');
  assert.equal(await page.getByRole('button', { name: 'Calculate exact ranges', exact: true }).count(), 0);
  const requestBody = response.request().postDataJSON();
  assert.equal(requestBody.options, undefined, 'Analysis should always use all completions of the partial tree');
  await page.getByLabel('Close analysis', { exact: true }).click();
  await page.locator('.split-choice').first().click();
  await page.getByRole('button', { name: 'Constrained', exact: true }).click();
  await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
  await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
  const infeasible = page.waitForResponse(r => r.url().includes('/api/complete?'));
  await page.getByRole('button', { name: 'Build optimal constrained completion', exact: true }).click();
  assert.equal((await infeasible).status(), 400);
  await page.locator('.constraint-message').filter({ hasText: 'No completion satisfies' }).waitFor();
  assert.equal(await page.locator('.arborenum-node-split').count(), 1);
  await page.locator('.constraint-close').click();
  await page.locator('.arborenum-node-split').click();
  await page.getByRole('button', { name: 'Constrained', exact: true }).click();
  await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
  await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
  const completion = page.waitForResponse(r => r.url().includes('/api/complete?'));
  await page.getByRole('button', { name: 'Build optimal constrained completion', exact: true }).click();
  const filledResponse = await completion;
  assert.equal(filledResponse.status(), 200, await filledResponse.text());
  const filled = await filledResponse.json();
  assert.equal(filled.leaves, 1); assert.equal(filled.abstained_samples, 0); assert.equal(filled.tree.kind, 'leaf');
  await page.locator('.constraint-modal').waitFor({ state: 'detached' });
  const fixed = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Analyze', exact: true }).click();
  const fixedResult = await (await fixed).json();
  assert.equal(fixedResult.tree_count, '1');
  assert.deepEqual(fixedResult.leaf_distribution, [{value: 1, count: '1', probability: 1}]);
  for (const row of fixedResult.disagreement) assert.equal(row.disagreement, 0);
  await page.getByLabel('Close analysis', { exact: true }).click();
  for (const mode of ['Ensure prediction', 'Both']) {
    await page.locator('.arborenum-node-leaf').click();
    await page.getByRole('button', { name: 'Constrained', exact: true }).click();
    await page.getByLabel('Maximum leaves', { exact: true }).fill('1');
    await page.getByLabel('Maximum abstained samples', { exact: true }).fill('0');
    await page.getByRole('button', { name: mode, exact: true }).click();
    if (mode === 'Both') await page.locator('.constraint-check-grid input').first().check();
    await page.getByLabel('Prediction to ensure', { exact: true }).selectOption('1');
    const pending = page.waitForResponse(r => r.url().includes('/api/complete?'));
    await page.getByRole('button', { name: mode === 'Both' ? 'Build optimal completion satisfying both' : 'Build optimal constrained completion', exact: true }).click();
    const response = await pending;
    assert.equal(response.status(), 200, await response.text());
    const result = await response.json();
    assert.equal(result.leaves, 1); assert.equal(result.abstained_samples, 0); assert.equal(result.tree.prediction, 1);
    await page.locator('.constraint-modal').waitFor({ state: 'detached' });
  }
  assert.equal(await page.evaluate(async () => (await (await fetch('/api/session')).json()).full_graph_exports), 0);
  await page.getByRole('button', { name: 'Upload', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Upload dataset' }).click();
  if (!(await page.getByRole('button', { name: 'Reset training settings', exact: true }).isVisible())) await page.locator('summary').filter({ hasText: 'Advanced training settings' }).click();
  await page.getByRole('button', { name: 'Reset training settings', exact: true }).click();
  await page.locator('.live-file input').setInputFiles({ name: 'multiclass.csv', mimeType: 'text/csv', buffer: Buffer.from('a,label\n0,one\n0,two\n0,three\n') });
  await page.getByLabel('Maximum depth', { exact: true }).fill('0');
  const started = page.waitForResponse(r => r.url().endsWith('/api/session') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Start ArborEnum', exact: true }).click();
  const newSid = (await (await started).json()).session_id;
  await page.waitForFunction(sid => window.ARBORENUM_CURRENT_BUILDER_PAYLOAD?.graph?.metadata?.session_id === sid, newSid);
  await page.waitForFunction(async () => ['finished', 'stopped'].includes((await (await fetch('/api/session')).json()).phase));
  const multiclass = page.waitForResponse(r => r.url().includes('/api/analyze?'));
  await page.getByRole('button', { name: 'Analyze', exact: true }).click();
  const multiResult = await (await multiclass).json();
  assert.equal(multiResult.class_count, 3); assert.equal(multiResult.abstention_enabled, false);
  await page.locator('.analysis-importance').waitFor();
  assert.equal(await page.locator('.analysis-distribution-abstention').count(), 0);
  assert.equal(await page.getByText('For each sample, the proportion of models differing from the most common prediction.', { exact: true }).count(), 1);
  await page.getByLabel('Close analysis', { exact: true }).click();
  console.log('Analysis ranges, majority disagreement, distribution hovers, conditional abstention and complete export passed');
}
module.exports = { exerciseAnalysis };
